    private void txtPasswordKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPasswordKeyReleased
        // TODO add your handling code here:
        if (txtPassword.getText().length() < 1) {
            btnClear.setEnabled(false);
            btnLogin.setEnabled(false);
        } else {
            btnClear.setEnabled(true);
            btnLogin.setEnabled(true);
        }

        if (comboRole.getSelectedItem().toString().equals("Customer") && txtPassword.getText().length() == 4) {
            btnLogin.requestFocus();
        } else if (comboRole.getSelectedItem().toString().equals("User") && txtPassword.getText().length() == 3) {
            btnLogin.requestFocus();
        } else if (comboRole.getSelectedItem().toString().equals("Admin") && txtPassword.getText().length() == 13) {
            btnLogin.requestFocus();
        }
    }//GEN-LAST:event_txtPasswordKeyReleased

