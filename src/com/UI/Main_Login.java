    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        String role = comboRole.getSelectedItem().toString();
        String Password = txtPassword.getText();
        String comMode = "UART";
        if (btnCAN.isSelected()) {
            comMode = "CAN";
        }

        if (role.equals("User") && Password.equals("123")) {
            setVisible(false);
            new index(date, role, comMode).setVisible(true);
        } else if (role.equals("Customer") && Password.equals("1234")) {
            setVisible(false);
            new index(date, role, comMode).setVisible(true);
        } else if (role.equals("Admin") && Password.equals("TECSAGE@ADMIN")) {
            setVisible(false);
            new index(date, role, comMode).setVisible(true);
        } else {
            JOptionPane.showMessageDialog(null, "Password is incorrect for Selected Role!");
        }

    }//GEN-LAST:event_btnLoginActionPerformed

